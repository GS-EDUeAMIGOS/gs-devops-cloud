-- -----------------------------------------------------
-- 1. USUARIO
-- -----------------------------------------------------

CREATE TABLE tb_vc_usuario (

    id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    nome VARCHAR2(120)
        NOT NULL,

    email VARCHAR2(150)
        NOT NULL,

    senha VARCHAR2(255)
        NOT NULL,

    role VARCHAR2(30)
        NOT NULL,

    possui_mobilidade_reduzida NUMBER(1,0)
        DEFAULT 0
        NOT NULL,

    criado_em TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    CONSTRAINT pk_vc_usuario
        PRIMARY KEY (id),

    CONSTRAINT ck_vc_usuario_role
        CHECK (role IN (
            'ROLE_ADMIN',
            'ROLE_CIDADAO'
        )),

    CONSTRAINT ck_vc_usuario_mobilidade
        CHECK (
            possui_mobilidade_reduzida IN (0, 1)
        )
);

-- Unicidade de email sem diferenciar maiusculas
-- e minusculas.

CREATE UNIQUE INDEX uk_vc_usuario_email
    ON tb_vc_usuario (LOWER(email));


-- -----------------------------------------------------
-- 2. LINHA FAVORITA
-- -----------------------------------------------------

CREATE TABLE tb_vc_linha_favorita (

    id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    codigo_linha NUMBER(10)
        NOT NULL,

    letreiro VARCHAR2(30)
        NOT NULL,

    sentido NUMBER(10)
        NOT NULL,

    terminal_origem VARCHAR2(120),

    terminal_destino VARCHAR2(120),

    apelido VARCHAR2(100),

    criado_em TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    usuario_id NUMBER(19)
        NOT NULL,

    CONSTRAINT pk_vc_linha_favorita
        PRIMARY KEY (id),

    CONSTRAINT fk_vc_linha_favorita_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES tb_vc_usuario(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_vc_linha_favorita_sentido
        CHECK (sentido IN (1, 2)),

    CONSTRAINT uk_vc_linha_favorita_usuario_linha
        UNIQUE (usuario_id, codigo_linha)
);


-- -----------------------------------------------------
-- 3. PARADA FAVORITA
-- -----------------------------------------------------

CREATE TABLE tb_vc_parada_favorita (

    id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    codigo_parada NUMBER(19)
        NOT NULL,

    nome_parada VARCHAR2(150)
        NOT NULL,

    endereco VARCHAR2(250),

    latitude FLOAT(53),

    longitude FLOAT(53),

    possui_rampa_acessivel NUMBER(1,0)
        DEFAULT 0
        NOT NULL,

    possui_piso_tatil NUMBER(1,0)
        DEFAULT 0
        NOT NULL,

    criado_em TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    usuario_id NUMBER(19)
        NOT NULL,

    CONSTRAINT pk_vc_parada_favorita
        PRIMARY KEY (id),

    CONSTRAINT fk_vc_parada_favorita_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES tb_vc_usuario(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_vc_parada_favorita_rampa
        CHECK (possui_rampa_acessivel IN (0, 1)),

    CONSTRAINT ck_vc_parada_favorita_piso
        CHECK (possui_piso_tatil IN (0, 1)),

    CONSTRAINT uk_vc_parada_favorita_usuario_parada
        UNIQUE (usuario_id, codigo_parada)
);


-- -----------------------------------------------------
-- 4. ALERTA
-- -----------------------------------------------------

CREATE TABLE tb_vc_alerta (

    id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    titulo VARCHAR2(120)
        NOT NULL,

    mensagem VARCHAR2(500)
        NOT NULL,

    codigo_linha NUMBER(10),

    codigo_parada NUMBER(19),

    somente_veiculo_acessivel NUMBER(1,0)
        DEFAULT 0
        NOT NULL,

    horario_notificacao VARCHAR2(20),

    ativo NUMBER(1,0)
        DEFAULT 1
        NOT NULL,

    criado_em TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    usuario_id NUMBER(19)
        NOT NULL,

    CONSTRAINT pk_vc_alerta
        PRIMARY KEY (id),

    CONSTRAINT fk_vc_alerta_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES tb_vc_usuario(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_vc_alerta_acessivel
        CHECK (somente_veiculo_acessivel IN (0, 1)),

    CONSTRAINT ck_vc_alerta_ativo
        CHECK (ativo IN (0, 1))
);


-- -----------------------------------------------------
-- 5. OCORRENCIA
-- -----------------------------------------------------

CREATE TABLE tb_vc_ocorrencia (

    id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    titulo VARCHAR2(120) NOT NULL,

    descricao VARCHAR2(1000) NOT NULL,

    tipo VARCHAR2(40) NOT NULL,

    status VARCHAR2(30) NOT NULL,

    gravidade VARCHAR2(20) NOT NULL,

    codigo_linha NUMBER(10),

    codigo_parada NUMBER(19),

    prefixo_veiculo VARCHAR2(30),

    afeta_acessibilidade NUMBER(1,0)
        DEFAULT 0
        NOT NULL,

    criado_em TIMESTAMP(6)
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,

    atualizado_em TIMESTAMP(6),

    usuario_id NUMBER(19) NOT NULL,

    CONSTRAINT pk_vc_ocorrencia
        PRIMARY KEY (id),

    CONSTRAINT fk_vc_ocorrencia_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES tb_vc_usuario(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_vc_ocorrencia_tipo
        CHECK (tipo IN (
            'ACESSIBILIDADE',
            'ELEVADOR_INOPERANTE',
            'LOTACAO_EXCESSIVA',
            'ATRASO',
            'SEGURANCA',
            'INFRAESTRUTURA_PARADA',
            'OUTROS'
        )),

    CONSTRAINT ck_vc_ocorrencia_status
        CHECK (status IN (
            'ABERTA',
            'EM_ANALISE',
            'CONFIRMADA',
            'RESOLVIDA',
            'ARQUIVADA'
        )),

    CONSTRAINT ck_vc_ocorrencia_gravidade
        CHECK (gravidade IN (
            'BAIXA',
            'MEDIA',
            'ALTA',
            'CRITICA'
        )),

    CONSTRAINT ck_vc_ocorrencia_acessibilidade
        CHECK (afeta_acessibilidade IN (0, 1))
);

